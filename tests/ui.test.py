# اختبار الواجهة: حكم + متسابقين اثنين على جوالات (Playwright)
import asyncio, os, sys
from playwright.async_api import async_playwright
BASE = os.environ.get("BASE", "http://127.0.0.1:8787")
SHOTS = os.environ.get("SHOTS", "/home/claude/shots")
fails = 0
def ok(c, m):
    global fails
    print(("✓ " if c else "✗ ") + m)
    if not c: fails += 1

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
        phone = dict(viewport={"width": 390, "height": 844}, device_scale_factor=2, is_mobile=True, has_touch=True, locale="ar")
        J = await (await b.new_context(viewport={"width": 430, "height": 932}, locale="ar")).new_page()
        A = await (await b.new_context(**phone)).new_page()
        B = await (await b.new_context(**phone)).new_page()
        errs = []
        for name, pg in (("judge", J), ("A", A), ("B", B)):
            pg.on("pageerror", lambda e, n=name: errs.append(f"{n}: {e}"))
        await J.goto(BASE + "/game.html")
        await J.click("#create-btn")
        await J.wait_for_selector("#s-lobby:not([hidden])")
        code = (await J.text_content("#l-code")).strip()
        ok(len(code) == 4, f"الحكم عمل غرفة {code}")
        for pg, nm in ((A, "سيف"), (B, "ليث")):
            await pg.goto(f"{BASE}/game.html?room={code}")
            await pg.wait_for_selector("#s-name:not([hidden])")
            await pg.fill("#name-in", nm)
            await pg.click("#name-form button")
            await pg.wait_for_selector("#s-player:not([hidden])")
        await J.wait_for_function("document.querySelectorAll('#l-teams .pchip').length === 2")
        ok(True, "المتسابقين دخلوا والحكم شافهم")
        await J.click('#l-sec [data-sec="45"]')
        await J.wait_for_selector('#l-sec [data-sec="45"][aria-pressed="true"]')
        await J.click('#l-sec [data-sec="30"]')
        await J.wait_for_selector('#l-sec [data-sec="30"][aria-pressed="true"]')
        ok(True, "اختيار وقت الدور شغّال")
        await J.screenshot(path=f"{SHOTS}/1-judge-lobby.png", full_page=True)
        await A.screenshot(path=f"{SHOTS}/2-player-lobby.png", full_page=True)
        await J.click("#l-start")
        await J.wait_for_selector("#s-pick:not([hidden])")
        await J.fill("#pick-in", "inception")
        await J.click("#pick-form button[type=submit]")
        # يا بيختاره لحاله أو بيعرض نتائج
        await J.wait_for_function("!document.querySelector('#s-play').hidden || document.querySelector('#sugg .result')", timeout=15000)
        if await J.is_hidden("#s-play"):
            await J.click("#sugg .result")
        await J.wait_for_selector("#s-play:not([hidden])", timeout=15000)
        ok(True, "الحكم اختار الفيلم")
        await A.wait_for_selector(".turn")
        await asyncio.sleep(1.2)
        cdA = await A.text_content(".turn [data-cd]")
        ok(cdA and 25 <= int(cdA) <= 30, f"المؤقت عم يعدّ على الجوال ({cdA})")
        mineA = await A.get_attribute(".turn", "class"); mineB = await B.get_attribute(".turn", "class")
        ok("mine" in mineA and "mine" not in mineB, "الفريق الأول شايف 'دوركم' والثاني شايف دور الثاني")
        await A.screenshot(path=f"{SHOTS}/3-player-myturn.png", full_page=True)
        await B.screenshot(path=f"{SHOTS}/4-player-waiting.png", full_page=True)
        await A.click("#p-hint")
        await A.wait_for_selector(".hint-feed .hcard")
        await asyncio.sleep(0.8)
        ok(await B.locator(".hint-feed .hcard").count() == 0, "التلميح وصل لفريق سيف بس، ليث ما شافه")
        await J.wait_for_selector(".gchip.t0")
        ok(True, "الحكم شاف مين أخذ التلميح")
        await A.screenshot(path=f"{SHOTS}/5-player-hint.png", full_page=True)
        await J.screenshot(path=f"{SHOTS}/6-judge-play.png", full_page=True)
        await J.click("#g-pass")
        await B.wait_for_selector(".turn.mine")
        ok(True, "الحكم ضغط جاوبت → الدور انتقل للفريق الثاني")
        await J.click("#g-pause")
        await A.wait_for_selector(".turn.paused")
        ok(True, "إيقاف الوقت بيبين عند المتسابقين")
        await J.click("#g-pause")
        await J.click('#g-who [data-win="1"]')
        await J.wait_for_selector("#s-reveal:not([hidden])")
        await A.wait_for_selector(".reveal-card")
        ok("Inception" in (await A.text_content(".reveal-card")), "بعد الكشف المتسابق شاف اسم الفيلم")
        await J.click("#r-end")
        await J.wait_for_selector("#s-final:not([hidden])")
        await A.wait_for_selector("#card-prev img", timeout=15000)
        await J.wait_for_selector("#card-prev img", timeout=15000)
        ok(True, "شاشة النتيجة النهائية وكرت الستوري جاهز")
        final = await A.text_content(".reveal-card")
        ok("فاز" in final, "النتيجة النهائية بتعلن الفائز")
        # حفظ الكرت نفسه كصورة
        data = await A.evaluate("""async () => { const img = document.querySelector('#card-prev img'); const r = await fetch(img.src); const b = await r.blob(); const a = new Uint8Array(await b.arrayBuffer()); let s=''; for (const x of a) s+=String.fromCharCode(x); return btoa(s); }""")
        import base64
        open(f"{SHOTS}/8-story-card.png", "wb").write(base64.b64decode(data))
        await A.screenshot(path=f"{SHOTS}/7-player-final.png", full_page=True)
        ok(not errs, "ما في أخطاء جافاسكربت" + ("" if not errs else ": " + " | ".join(errs[:3])))
        await b.close()
    print("\nكل اختبارات الواجهة نجحت" if not fails else f"\n{fails} فشل")
    sys.exit(1 if fails else 0)
asyncio.run(main())
